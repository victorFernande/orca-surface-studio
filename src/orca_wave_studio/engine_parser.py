"""Strict reader for the labelled, single-tool Orca benchmark G-code dialect."""

from __future__ import annotations

import math
import re
from dataclasses import dataclass

from .contracts import WaveError

NUM = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)"
WORD = re.compile(r"([A-Za-z])\s*(" + NUM + ")")
LABEL = re.compile(
    r"^(stop printing object|printing object)\b.*?\bid\s*:\s*(\d+)\s+copy\s+(\d+)\s*$",
    re.IGNORECASE,
)
SAFE = {
    "M73",
    "M104",
    "M105",
    "M106",
    "M107",
    "M109",
    "M140",
    "M141",
    "M190",
    "M191",
    "M201",
    "M203",
    "M204",
    "M205",
    "M400",
    "M900",
    "G4",
    "G21",
}
OUTER = {"outer wall", "external perimeter"}
KNOWN_ROLES = OUTER | {
    "inner wall",
    "perimeter",
    "overhang wall",
    "overhang perimeter",
    "sparse infill",
    "internal infill",
    "internal solid infill",
    "solid infill",
    "top surface",
    "top solid infill",
    "bottom surface",
    "bottom solid infill",
    "bridge",
    "bridge infill",
    "internal bridge",
    "gap infill",
    "gap fill",
    "support",
    "support material",
    "support interface",
    "support material interface",
    "support transition",
    "support base",
    "skirt",
    "brim",
    "skirt/brim",
    "prime tower",
    "wipe tower",
    "ironing",
}


@dataclass
class Move:
    i: int
    start: tuple
    end: tuple
    de: float
    e: float
    f: float
    xyz_abs: bool
    e_abs: bool
    fields: dict
    cmd: str
    obj: str | None
    label: tuple | None
    role: str
    layer: int
    z: float | None
    h: float | None
    w: float | None
    comment: str

    @property
    def deposits(self):
        return self.de > 0 and self.start[:2] != self.end[:2]


@dataclass
class Parsed:
    lines: list
    moves: dict
    resets: set
    barrier: set
    seen: set
    roles: dict
    loops: list


def read(source, selection, mapping):
    lines = source.decode("latin1").splitlines(keepends=True)
    moves, roles, loops = {}, {}, []
    resets, barrier, seen = set(), set(), set()
    xyz = (None,) * 3
    e = feed = 0.0
    retract_debt = 0.0
    motors_released = False
    absolute = e_abs = True
    layer = -1
    z = h = width = None
    active = None
    role = ""
    # Native Orca serializes a TYPE comment only when the role changes, even
    # across layer and object delimiters. Do not infer this for unknown emitters.
    modal_roles = any(
        re.match(r"^;\s*generated by OrcaSlicer\b", ln, re.IGNORECASE)
        for ln in lines[:12]
    )
    progress_lines = set()
    profile_width = None
    for line in lines:
        m = re.fullmatch(
            r"\s*;\s*outer_wall_line_width\s*=\s*(" + NUM + r")\s*", line, re.IGNORECASE
        )
        if m:
            profile_width = float(m[1])
    for i, line in enumerate(lines):
        body, sep, comment = line.partition(";")
        body, comment = body.strip(), comment.strip()
        if not body:
            if not sep:
                continue
            label = LABEL.match(comment)
            if label:
                key = int(label[2]), int(label[3])
                if label[1].lower().startswith("stop"):
                    if active != key:
                        raise WaveError("Fim de objeto sem início correspondente.")
                    active = None
                else:
                    if active is not None or key[0] not in mapping:
                        raise WaveError(
                            "Rótulo de objeto sobreposto ou sem mapeamento."
                        )
                    active = key
                    seen.add(key)
                if not modal_roles:
                    role = ""
            elif re.match(
                r"(stop printing object|printing object|start printing object)\b",
                comment,
                re.IGNORECASE,
            ):
                raise WaveError("Formato de rótulo de objeto desconhecido.")
            elif comment.upper() in {"LAYER_CHANGE", "CHANGE_LAYER"}:
                layer += 1
                z = h = None
                if not modal_roles:
                    role = ""
            else:
                m = re.fullmatch(
                    r"(Z|HEIGHT|LAYER_HEIGHT|WIDTH|LINE_WIDTH|TYPE|FEATURE)\s*:\s*(.*)",
                    comment,
                    re.IGNORECASE,
                )
                if m:
                    tag, v = m[1].upper(), m[2].strip()
                    if tag in {"TYPE", "FEATURE"}:
                        role = v.lower()
                    elif re.fullmatch(NUM, v) and math.isfinite(float(v)):
                        if tag == "Z":
                            z = float(v)
                        elif tag in {"HEIGHT", "LAYER_HEIGHT"}:
                            h = float(v)
                        else:
                            width = float(v)
                    else:
                        raise WaveError("Metadado geométrico inválido.")
            continue
        command = re.match(r"([GMT]\d+)\s*(.*)$", body, re.IGNORECASE)
        if not command:
            raise WaveError(f"Linha {i + 1}: comando fora do dialeto de bancada.")
        cmd, args = command[1].upper(), command[2]
        if cmd in {"M18", "M84"} and (not args or re.fullmatch(r"(?:[XYZE]\s*)+",args,re.I)):
            motors_released = True
            continue
        if motors_released and cmd.startswith("G") and cmd not in {"G4", "G21"}:
            raise WaveError("Movimento após desligamento dos motores fora do piloto.")
        if cmd in {"G90", "G91", "M82", "M83"} and not args:
            if cmd in {"G90", "G91"}:
                absolute = cmd == "G90"
                # Marlin resets its extrusion override on G90/G91. Require an
                # explicit E mode if independent-mode firmware could disagree.
                if e_abs != absolute:
                    e_abs = None
            else:
                e_abs = cmd == "M82"
            barrier.add(i)
            continue
        if cmd in SAFE:
            if "*" in args:
                raise WaveError("G-code com checksum não suportado.")
            if cmd == "M73":
                progress_lines.add(i)
            continue
        if layer < 0 and cmd in {"M220", "M221"} and re.fullmatch(r"S\s*100(?:\.0+)?",args,re.I):
            # Stock SV06 resets speed/flow to 100%; no non-default factors
            # are inferred or silently applied to the transformed deposition.
            continue
        if layer < 0 and cmd == "M420" and re.fullmatch(r"S\s*[01](?:\s+Z\s*"+NUM+r")?",args,re.I):
            # Preview coordinates are nominal. Mesh compensation remains a
            # firmware operation, not evidence of physical surface clearance.
            continue
        if cmd == "T0" and not args:
            continue
        if cmd == "G28" and not moves:
            xyz = (None,) * 3
            continue
        if cmd not in {"G0", "G1", "G92"}:
            raise WaveError(
                f"Linha {i + 1}: {cmd} fora do piloto linear de ferramenta única."
            )
        words = WORD.findall(args)
        fields = {k.upper(): float(v) for k, v in words}
        if (
            WORD.sub("", args).strip()
            or len(words) != len(fields)
            or not set(fields) <= set("XYZEF")
            or not all(map(math.isfinite, fields.values()))
        ):
            raise WaveError(f"Linha {i + 1}: parâmetros de movimento incompatíveis.")
        if cmd == "G92":
            if not fields or "F" in fields:
                raise WaveError("G92 sem eixos conhecidos.")
            xyz = tuple(fields.get(k, old) for k, old in zip("XYZ", xyz))
            if "E" in fields:
                e = fields["E"]
                resets.add(i)
            if any(k in fields for k in "XYZ"):
                barrier.add(i)
            continue
        end = list(xyz)
        for j, k in enumerate("XYZ"):
            if k in fields:
                if not absolute and xyz[j] is None:
                    raise WaveError("Coordenada relativa sem origem conhecida.")
                end[j] = fields[k] if absolute else xyz[j] + fields[k]
        if "E" in fields and e_abs is None:
            raise WaveError("Declare M82/M83 após G90/G91 para definir o modo de E.")
        new_e = fields.get("E", e) if e_abs else e + fields.get("E", 0)
        feed = fields.get("F", feed)
        obj = mapping[active[0]] if active is not None else None
        m = Move(
            i,
            xyz,
            tuple(end),
            new_e - e,
            new_e,
            feed,
            absolute,
            e_abs,
            fields,
            cmd,
            obj,
            active,
            role,
            layer,
            z,
            h,
            width or profile_width,
            comment,
        )
        moves[i] = m
        if m.deposits:
            if (
                obj is None
                and layer >= 0
                and role
                not in {"prime tower", "wipe tower", "skirt", "brim", "skirt/brim"}
            ):
                raise WaveError(
                    "Deposição sem identificação inequívoca de objeto ou purga."
                )
            if obj in selection:
                if (
                    role not in KNOWN_ROLES
                    or layer < 0
                    or z is None
                    or h is None
                    or h <= 0
                ):
                    raise WaveError(
                        "Extrusão sem papel, camada, Z ou altura inequívocos."
                    )
                roles.setdefault((active, layer), set()).add(role)
                if role in OUTER:
                    if retract_debt > 1e-7:
                        raise WaveError(
                            "Recuperação de retração misturada à deposição do perímetro."
                        )
                    if (
                        None in xyz
                        or None in end
                        or abs(xyz[2] - z) > 0.00002
                        or abs(end[2] - z) > 0.00002
                        or feed <= 0
                    ):
                        raise WaveError(
                            "Perímetro de origem deve ser planar, com posição e F conhecidos."
                        )
                    same = (
                        loops
                        and loops[-1][-1].label == active
                        and loops[-1][-1].layer == layer
                        and all(
                            j in progress_lines for j in range(loops[-1][-1].i + 1, i)
                        )
                    )
                    if not same:
                        loops.append([])
                    loops[-1].append(m)
        retract_debt = max(0.0, retract_debt - m.de)
        xyz, e = tuple(end), new_e
    if active is not None:
        raise WaveError("Rótulo de objeto sem fechamento.")
    if not set(selection) <= {mapping[key[0]] for key in seen}:
        raise WaveError("Objeto selecionado sem rótulo verificável.")
    return Parsed(lines, moves, resets, barrier, seen, roles, loops)
