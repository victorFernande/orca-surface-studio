from __future__ import annotations

import math
from pathlib import Path
import struct

from .contracts import ProjectSnapshot
from .geometry import IDENTITY


def cylinder_mesh(radius: float = 20., height: float = 8., segments: int = 320):
    vertices = [[radius*math.cos(2*math.pi*i/segments), radius*math.sin(2*math.pi*i/segments), z]
                for z in (0., height) for i in range(segments)]
    vertices.extend([[0., 0., 0.], [0., 0., height]])
    triangles = []
    for i in range(segments):
        j = (i+1) % segments
        triangles.extend([[i, j, j+segments], [i, j+segments, i+segments],
                          [2*segments, j, i], [2*segments+1, i+segments, j+segments]])
    return vertices, triangles


def cylinder_snapshot(*, plate_index: int = 0, two_objects: bool = False) -> ProjectSnapshot:
    vertices, triangles = cylinder_mesh()
    objects = []
    for i in range(2 if two_objects else 1):
        matrix = [row[:] for row in IDENTITY]
        matrix[0][3] = 60. + 60*i
        matrix[1][3] = 60.
        objects.append({"id": str(100+i), "name": "Cilindro de bancada", "config": {},
                        "instances_data": [{"id": str(200+i), "matrix": matrix, "printable": True}],
                        "volumes": [{"id": str(300+i), "kind": "part", "negative": False,
                                     "matrix": IDENTITY, "vertices": vertices, "triangles": triangles,
                                     "manifold": True}]})
    return ProjectSnapshot("bench-cylinder", plate_index, tuple(objects),
                           {"layer_height": "0.2", "nozzle_diameter": "0.4", "wall_loops": "1",
                            "gcode_flavor": "marlin", "gcode_label_objects": "1", "filament_type": "PETG"})


def cylinder_gcode(*, layers: int = 40, two_objects: bool = False) -> bytes:
    rows = ["; generated by Orca Wave Studio integration fixture; BENCH ONLY",
            "; filament_diameter = 1.75", "; filament_density = 1.27", "G90", "M83", "G92 E0",
            ";WIDTH:0.42", ";HEIGHT:0.2", "M104 S0", "M140 S0"]
    count = 320
    extrusion = (.42-.2*(1-math.pi/4))*.2 * (40*math.sin(math.pi/count)) / (math.pi*1.75**2/4)
    for layer in range(layers):
        z = .2*(layer+1)
        rows.extend([";LAYER_CHANGE", f";Z:{z:.5f}", ";HEIGHT:0.2"])
        for obj in range(2 if two_objects else 1):
            x, y = 60.+60*obj, 60.
            rows.extend([f"; printing object Cilindro id:{obj} copy 0", f"G0 X{x+20:.5f} Y{y:.5f} Z{z:.5f} F6000",
                         ";TYPE:Outer wall", ";WIDTH:0.42"])
            for i in range(1,count+1):
                angle=2*math.pi*i/count
                rows.append(f"G1 X{x+20*math.cos(angle):.5f} Y{y+20*math.sin(angle):.5f} E{extrusion:.7f} F1200")
            rows.append(f"; stop printing object Cilindro id:{obj} copy 0")
    rows.extend([";TYPE:Custom", "M104 S0", "M140 S0", "M84"])
    return ("\n".join(rows)+"\n").encode()


def write_cylinder_stl(path: Path) -> None:
    vertices, triangles = cylinder_mesh()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as stream:
        stream.write(b"Orca Wave integration cylinder".ljust(80, b"\0"))
        stream.write(struct.pack("<I",len(triangles)))
        for triangle in triangles:
            stream.write(struct.pack("<12fH",0,0,0,*(v for i in triangle for v in vertices[i]),0))
