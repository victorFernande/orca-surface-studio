import math
import unittest

from orca_wave_studio.roof_audit import Bead,BeadIndex,_surface,_support,audit_head_path


class Plane:
    bounds_xy=((0.,2.),(0.,2.))
    top_plane=(math.tan(math.radians(25)),0.,1.)
    bottom_plane=(top_plane[0],0.,.8)

    def surface_is_exposed(self,x,y,face):return True
    def expected_surface(self,x,y,face):
        p=self.top_plane if face=='top' else self.bottom_plane
        return p[0]*x+p[1]*y+p[2]


class RoofAuditTests(unittest.TestCase):
    def test_swept_bead_interval_finds_extremum_inside_segment(self):
        bead=Bead((0,0,1),(2,0,2),.2,.3,.4,1,'top surface')
        self.assertEqual(bead.interval_at(3,0),None)
        bottom,top=bead.interval_at(1,0)
        self.assertAlmostEqual(top,1.6)
        self.assertAlmostEqual(bottom,1.16)

    def test_surface_samples_can_refute_but_never_certify_entire_face(self):
        warp=Plane();m=warp.top_plane[0]
        beads=[Bead((0,y,1),(2,y,1+2*m),.2,.2,.4,1,'top surface') for y in (.1,.5,.9,1.3,1.7,1.9)]
        report=_surface(BeadIndex(beads),warp,'top',.1,.05)
        self.assertEqual(report['status'],'FAIL_ESTIMATE_WITNESS')
        self.assertGreater(report['sampled_max_normal_error_mm'],.08)
        self.assertFalse(report['maximum_over_entire_face_certified'])
        flat=Plane();flat.top_plane=(0.,0.,1.)
        beads=[Bead((0,y,1),(2,y,1),.2,.2,.4,1,'top surface') for y in (.1,.5,.9,1.3,1.7,1.9)]
        clean=_surface(BeadIndex(beads),flat,'top',.1,.05)
        self.assertEqual(clean['status'],'NOT_CERTIFIED')
        self.assertEqual(clean['sampled_max_normal_error_mm'],0.)

    def test_support_intersection_is_separate_from_roof_finish(self):
        plane=Plane();plane.bottom_plane=(0.,0.,.8)
        index=BeadIndex([Bead((0,1,1),(2,1,1),.2,.2,.5,3,'support interface')])
        model=BeadIndex([Bead((0,1,1.2),(2,1,1.2),.4,.4,.5,4,'bottom surface')])
        report=_support(index,plane,.1,.2,model)
        self.assertEqual(report['status'],'FAIL_ESTIMATE_INTERSECTION')
        self.assertGreater(report['uncovered_samples'],0)
        self.assertFalse(report['order_and_removability_validated'])

    def test_positive_support_gap_to_mesh_can_hide_overlap_with_deposited_bead(self):
        plane=Plane();plane.bottom_plane=(0.,0.,1.)
        supports=BeadIndex([Bead((0,1,.95),(2,1,.95),.2,.2,.5,3,'support interface')])
        model=BeadIndex([Bead((0,1,1.2),(2,1,1.2),.3,.3,.5,4,'bottom surface')])
        report=_support(supports,plane,.1,.2,model)
        self.assertGreater(report['sampled_support_to_target_mesh_normal_gap_range_mm'][0],0)
        self.assertLess(report['sampled_normal_gap_range_mm'][0],0)
        self.assertEqual(report['status'],'FAIL_ESTIMATE_INTERSECTION')
        self.assertAlmostEqual(report['intersection_witnesses'][0]['vertical_overlap_mm'],.05)

    def test_adapter_preserves_support_role_order_and_unknown_head_gate(self):
        from orca_wave_studio.regional_shell import RegionalShellWarp
        from orca_wave_studio.roof_fixtures import roof_coupon
        warp=RegionalShellWarp(roof_coupon(20)[0],'1')
        source=b'''; generated by OrcaSlicer 2.5.1
G90
M83
G1 X106 Y106 Z0.2 F1200
;LAYER_CHANGE
;Z:0.2
;HEIGHT:0.2
; printing object coupon id:0 copy 0
;TYPE:Support interface
;WIDTH:0.4
G1 X108 E0.1
G1 Y108 F5000
; stop printing object coupon id:0 copy 0
'''
        audit=audit_head_path(source,warp,{0:'1'},'1')
        self.assertEqual(audit['status'],'UNKNOWN')
        self.assertIn('MISSING_REAL_HEAD_PROFILE',audit['reason_codes'])
        self.assertEqual(audit['material_roles'],{'support interface':1})
        self.assertEqual(audit['material_count'],1)
        self.assertEqual(audit['motion_count'],2)
        self.assertFalse(audit['print_allowed'])
