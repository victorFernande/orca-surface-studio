"""Conformal study regressions use only memory and labelled G-code snippets."""
import math
from types import SimpleNamespace
import unittest

from orca_wave_studio.conformal import process_conformal_gcode
from orca_wave_studio.contracts import WaveError
from orca_wave_studio.engine_parser import read


MAPPING = {0: "torus", 1: "control"}


class AffineCell:
    anchor_z = 1.0
    object_id = "torus"
    settings = SimpleNamespace(step_mm=.4, min_segment_mm=.15, tolerance_mm=.02)

    def __init__(self, identity=False):
        self.identity = identity

    def local_scale(self, x, y):
        return 1.0 if self.identity else .8 + .05 * x

    def map_point(self, p):
        x, y, z = p
        return x, y, z if z <= self.anchor_z else self.anchor_z + (z - self.anchor_z) * self.local_scale(x, y)

    def normal_gap(self, x, y, z, h):
        span = self.map_point((x, y, z))[2] - self.map_point((x, y, z-h))[2]
        slope = 0 if self.identity else max(0, z-self.anchor_z) * .05
        return span / math.sqrt(1+slope*slope)

    def surface_heights(self, x, y):
        flat_top = 2.1
        return self.map_point((x, y, flat_top))[2], flat_top

    def chord_error_bound(self, a, b, p, q):
        # A test path with fixed XY or a planar deposition is piecewise affine.
        checks = [0, .5, 1]
        if a[2] != b[2]:
            checks += [max(0,min(1,(self.anchor_z-a[2])/(b[2]-a[2])))]
        return max(math.dist(self.map_point(tuple(x+t*(y-x) for x,y in zip(a,b))),
                             tuple(x+t*(y-x) for x,y in zip(p,q))) for t in checks)


def source(*, z=2.0, absolute=False):
    lines = ["; generated by OrcaSlicer 2.5.1", "G90", "M82" if absolute else "M83",
             "G92 E0", "G1 X-1 Y0 Z0.2 F1200", ";LAYER_CHANGE", f";Z:{z}", ";HEIGHT:0.2",
             "; printing object A id:0 copy 0", f"G1 Z{z} F1200", ";TYPE:Outer wall", ";WIDTH:0.42",
             "G1 X1 E2", "G1 E1.5 ;retract" if absolute else "G1 E-0.5 ;retract",
             "G1 E2 ;recover" if absolute else "G1 E0.5 ;recover", "G1 X0 Y-1 F6000",
             ";TYPE:Sparse infill", "G1 Y1 E4 F1200" if absolute else "G1 Y1 E2 F1200",
             ";TYPE:Top surface", "G1 Y1.05 E4.05" if absolute else "G1 Y1.05 E0.05",
             "G1 Y1.5 E4.5" if absolute else "G1 Y1.5 E0.45",
             "; stop printing object A id:0 copy 0",
             "; printing object B id:1 copy 0", "G1 X6 Y1.05 F6000",
             ";TYPE:Inner wall", "G1 X7 E5.5 F900 ;untouched" if absolute else "G1 X7 E1 F900 ;untouched",
             "; stop printing object B id:1 copy 0", "G92 E0", "G1 E-0.5 ;after-reset",
             "M73 P90 R1", "; estimated first layer printing time (normal mode) = 5s",
             "; estimated printing time (normal mode) = 30s", "; max_z_height: 123", "M107"]
    return ("\r\n".join(lines)+"\r\n").encode()


def process(code, warp=None):
    return process_conformal_gcode(code, warp or AffineCell(), MAPPING, "torus")


def areas(result):
    by_role = {}
    parsed = read(result.gcode, set(), MAPPING)
    for m in parsed.moves.values():
        if m.deposits:
            key = m.obj, m.role
            by_role[key] = by_role.get(key, 0) + m.de
    return parsed, by_role


class ConformalGcodeTests(unittest.TestCase):
    def test_native_support_metadata_rounding_is_not_a_nonplanar_source(self):
        code=source().replace(b';Z:2.0',b';Z:2.0004').replace(b';TYPE:Outer wall',b';TYPE:Support interface')
        result=process(code)
        self.assertEqual(result.report['source_z_metadata_rounding_allowance_mm'],.000501)
        with self.assertRaises(WaveError):
            process(code.replace(b';Z:2.0004',b';Z:2.0006'))
        with self.assertRaises(WaveError):
            process(code.replace(b'G1 X1 E2',b'G1 X1 Z2.0003 E2'))

    def test_native_zaa_is_not_transformed_or_extruded_twice(self):
        with self.assertRaisesRegex(WaveError,'Z Contouring'):
            process(source()+b'; zaa_enabled = 1\r\n')

    def test_piecewise_cell_jacobian_is_used_instead_of_top_only_scale(self):
        from orca_wave_studio.conformal import _gap_and_scale
        warp=AffineCell()
        warp.volume_scale=lambda x,y,z,h:.63
        gap,scale=_gap_and_scale(warp,(0,0,2),.2)
        self.assertAlmostEqual(scale,.63)
        self.assertGreater(gap,0)

    def test_jacobian_for_two_raster_directions_and_short_native_edge(self):
        result = process(source())
        parsed, by_role = areas(result)
        self.assertAlmostEqual(by_role["torus","outer wall"], 1.6, places=6)
        self.assertAlmostEqual(by_role["torus","sparse infill"], 1.6, places=6)
        self.assertAlmostEqual(by_role["torus","top surface"], .4, places=6)
        self.assertAlmostEqual(by_role["control","inner wall"], 1, places=6)
        self.assertIn(b"G1 X7 E1 F900 ;untouched\r\n", result.gcode)
        self.assertFalse(result.report["print_allowed"])
        self.assertEqual(result.report["coalesced_short_source_edges"], 1)
        self.assertGreaterEqual(result.report["min_subdivided_segment_mm"], .15-2e-6)
        self.assertEqual(result.report["short_native_edges"]["xyz_changed"], 0)
        self.assertEqual(result.report["short_native_edges"]["e_delta_changed"], 0)
        roof = result.report["top_layer_roof_audit"]
        self.assertEqual(roof["native_plane_z_mm"], 2.0)
        self.assertEqual(roof["outside_mesh_projection"], 0)
        self.assertAlmostEqual(roof["flat_roof_minus_native_z_range_mm"][0], .1)
        self.assertAlmostEqual(roof["original_roof_minus_emitted_z_range_mm"][0], .075)
        self.assertLessEqual(result.report["max_z_speed_mm_s"], 5)
        self.assertLessEqual(result.report["max_z_acceleration_mm_s2"], 50)
        self.assertLessEqual(result.report["max_geometric_error_mm"], .02)
        self.assertTrue(all(m.cmd in ("G0","G1") for m in parsed.moves.values()))
        other = next(m for m in parsed.moves.values() if m.obj=="control" and m.deposits)
        self.assertEqual(other.start, (6,1.05,2))
        self.assertEqual(other.end, (7,1.05,2))

    def test_absolute_e_mode_reset_and_signed_retraction(self):
        result = process(source(absolute=True))
        parsed, by_role = areas(result)
        self.assertAlmostEqual(by_role["torus","sparse infill"], 1.6, places=6)
        self.assertAlmostEqual(by_role["control","inner wall"], 1, places=6)
        special = {m.comment:m.de for m in parsed.moves.values() if m.comment in ("retract","recover","after-reset")}
        self.assertEqual(special, {"retract":-.5, "recover":.5, "after-reset":-.5})
        self.assertIn(b"G92 E0\r\nG1 E-0.5 ;after-reset", result.gcode)

    def test_cell_straddling_anchor_and_planar_identity(self):
        for z, warp, factor in [(1.1, AffineCell(), .9), (.2, AffineCell(), 1), (2, AffineCell(True), 1)]:
            with self.subTest(z=z,factor=factor):
                result = process(source(z=z),warp)
                _, by_role = areas(result)
                for role in ("outer wall","sparse infill"):
                    self.assertAlmostEqual(by_role["torus",role], 2*factor, places=6)
                if factor==1:
                    self.assertAlmostEqual(result.report["total_e_delta"], 0, places=6)
                    for a,b in zip(result.report["original_points"],result.report["deformed_points"]):
                        self.assertLess(math.dist(a,b), 2e-6)

    def test_commands_estimates_and_preview_continuity(self):
        result = process(source())
        self.assertNotIn(b"M73", result.gcode)
        self.assertNotIn(b"estimated first layer printing time", result.gcode)
        self.assertNotIn(b"max_z_height: 123", result.gcode)
        self.assertIn(b"M107\r\n", result.gcode)
        r=result.report
        self.assertEqual(len(r["original_points"]),len(r["deformed_points"]))
        self.assertEqual(len(r["layer_ids"]),len(r["original_points"]))
        self.assertEqual(len(r["break_indices"]),3)
        self.assertEqual(r["break_indices"][0],0)
        with self.assertRaises(WaveError):
            process(result.gcode)

    def test_changed_short_edge_needs_a_certified_neighbour(self):
        # The isolated final edge has no adjacent deposition of the same role.
        missing = source().replace(b"G1 Y1.5 E0.45\r\n", b"")
        with self.assertRaisesRegex(WaveError, "união certificada"):
            process(missing)
        # Reversing back to the same XY collapses the proposed two-edge chord.
        cusp = source().replace(b"G1 Y1.5 E0.45", b"G1 Y1 E0.05")
        with self.assertRaisesRegex(WaveError, "união certificada"):
            process(cusp)
        flat = process(missing, AffineCell(identity=True))
        self.assertIn(b"G1 Y1.05 E0.05\r\n", flat.gcode)
        self.assertEqual(flat.report["short_native_edges"]["xyz_changed"], 0)

    def test_native_corner_proposal_is_explicit_and_preserves_xy_and_flow(self):
        native=source().replace(b'G1 Y1.5 E0.45\r\n',b'')
        with self.assertRaisesRegex(WaveError,'união certificada'):
            process(native)
        warp=AffineCell()
        warp.settings=SimpleNamespace(step_mm=.4,min_segment_mm=.15,tolerance_mm=.02,
                                      retain_native_short_edges=True)
        result=process(native,warp)
        parsed,by_role=areas(result)
        edge=next(m for m in parsed.moves.values() if m.deposits and m.role=='top surface')
        self.assertEqual(edge.start[:2],(0.,1.))
        self.assertEqual(edge.end[:2],(0.,1.05))
        self.assertAlmostEqual(by_role['torus','top surface'],.05*.8,places=7)
        self.assertEqual(result.report['inherited_mapped_short_deposition_segments'],1)
        self.assertTrue(result.report['native_short_edge_proposal'])
        self.assertFalse(result.report['print_allowed'])

    def test_width_tag_and_source_flow_during_union(self):
        native = source().replace(b"G1 Y1.5 E0.45", b";WIDTH:0.45\r\nG1 Y1.5 E0.9")
        result = process(native)
        _, by_role = areas(result)
        self.assertAlmostEqual(by_role["torus", "top surface"], (.9+.05)*.8, places=7)
        self.assertIn(b";WIDTH:0.45\r\n", result.gcode)
        first = result.report["break_indices"][-1]
        points = result.report["deformed_points"][first:]
        for a, b in zip(points, points[1:]):
            self.assertGreaterEqual(math.dist(a,b), .15)
            self.assertLessEqual(math.dist(a,b), .4)

    def test_three_short_edges_are_joined_without_losing_material(self):
        native = source().replace(b"G1 Y1.05 E0.05\r\nG1 Y1.5 E0.45",
                                 b"G1 Y1.06 E0.06\r\nG1 Y1.12 E0.06\r\nG1 Y1.18 E0.06")
        result = process(native)
        _, by_role = areas(result)
        self.assertAlmostEqual(by_role['torus','top surface'], .18*.8, places=7)
        self.assertEqual(result.report['source_deposition_moves_by_role']['top surface'], 3)
        self.assertEqual(result.report['coalesced_short_source_edges'], 1)
        self.assertGreaterEqual(result.report['min_subdivided_segment_mm'], .15-2e-6)

    def test_unsupported_modes_and_ambiguous_extrusion_fail_closed(self):
        for before, after in [(b"G90", b"G91"), (b"G1 Y1 E2", b"G2 Y1 E2"),
                              (b";TYPE:Outer wall", b";TYPE:Bad role"),
                              (b"G1 E0.5 ;recover", b"G1 E0.2 ;recover"),
                              (b"M107", b"G92 X7")]:
            with self.subTest(replacement=after), self.assertRaises(WaveError):
                process(source().replace(before, after))
