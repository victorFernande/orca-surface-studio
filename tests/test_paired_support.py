import math
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
from orca_wave_studio.roof_fixtures import roof_coupon
from orca_wave_studio.regional_shell import RegionalShellWarp
from orca_wave_studio.paired_support import with_paired_support_gap
from orca_wave_studio.conformal import process_conformal_gcode
from orca_wave_studio.engine_parser import read
from orca_wave_studio.contracts import WaveError


SOURCE = b'''; generated by OrcaSlicer 2.5.1
G90
M83
G1 X105 Y110 Z0.2 F1200
;LAYER_CHANGE
;Z:7.2
;HEIGHT:0.2
; printing object roof id:0 copy 0
G1 Z7.2
;TYPE:Support interface
;WIDTH:0.4
G1 X115 E1
;LAYER_CHANGE
;Z:9.8
;HEIGHT:0.2
;TYPE:Outer wall
G1 X110 Y110 Z9.8
G1 X111 E1
;LAYER_CHANGE
;Z:7.2
;HEIGHT:0.2
;TYPE:Support interface
G1 X105 Y110 Z7.2
G1 X115 E1
; stop printing object roof id:0 copy 0
'''


class PairedSupportTests(unittest.TestCase):
    def setUp(self):
        snapshot, truth = roof_coupon(25)
        self.warp = RegionalShellWarp(snapshot, '1', {'retain_native_short_edges': True}, region=truth['roof'])

    def test_ceiling_has_constant_vertical_clearance_and_fixed_base(self):
        result = with_paired_support_gap(self.warp, SOURCE, {0: '1'}, '1', vertical_gap_mm=.35)
        field = result.support_warp
        for x in (105, 107, 110, 115):
            tip = field.map_point((x, 110, 7.2))
            self.assertAlmostEqual(result.expected_surface(x, 110, 'underside') - tip[2], .35)
            self.assertEqual(field.map_point((x, 110, 1)), (x, 110, 1))
            self.assertAlmostEqual(field.flatten_point(tip)[2], 7.2)
        self.assertFalse(hasattr(self.warp, 'support_warp'))
        self.assertFalse(result.summary['independent_support_field']['print_allowed'])

    def test_model_preserved_support_flow_and_bidirectional_travel_are_continuous(self):
        baseline = process_conformal_gcode(SOURCE, self.warp, {0: '1'}, '1')
        warp = with_paired_support_gap(self.warp, SOURCE, {0: '1'}, '1', vertical_gap_mm=.35)
        adjusted = process_conformal_gcode(SOURCE, warp, {0: '1'}, '1')
        before = [m for m in read(baseline.gcode, set(), {0: '1'}).moves.values() if m.deposits and m.role == 'outer wall']
        after = [m for m in read(adjusted.gcode, set(), {0: '1'}).moves.values() if m.deposits and m.role == 'outer wall']
        self.assertEqual([(m.start, m.end, m.fields['E']) for m in before], [(m.start, m.end, m.fields['E']) for m in after])
        support = [m for m in read(adjusted.gcode, set(), {0: '1'}).moves.values() if m.deposits and 'support' in m.role]
        # Two identical 10 mm paths, each E=1 before deformation. The support
        # field's column Jacobian is linear in X, so this integral is exact.
        expected = 2 * sum((3 + math.tan(math.radians(25)) * x - .35 - 1) / (7.2-1)
                           for x in (0, 10)) / 2
        self.assertAlmostEqual(sum(m.de for m in support), expected, places=6)
        for m in support:
            self.assertAlmostEqual(m.end[2], warp.expected_surface(*m.end[:2], 'underside') - .35, places=5)
        self.assertLessEqual(adjusted.report['max_geometric_error_mm'], .02)

    def test_ambiguous_owner_and_duplicate_mapping_are_rejected(self):
        with self.assertRaises(WaveError):
            with_paired_support_gap(self.warp, SOURCE, {0: 'other'}, '1', vertical_gap_mm=.35)
        attached = with_paired_support_gap(self.warp, SOURCE, {0: '1'}, '1', vertical_gap_mm=.35)
        with self.assertRaises(WaveError):
            with_paired_support_gap(attached, SOURCE, {0: '1'}, '1', vertical_gap_mm=.35)

    def test_absolute_extrusion_and_following_reset_keep_their_state(self):
        source = SOURCE.replace(b'M83', b'M82').replace(b'G1 X111 E1', b'G1 X111 E2')
        index = source.rfind(b'G1 X115 E1')
        source = source[:index] + source[index:].replace(b'G1 X115 E1', b'G1 X115 E3', 1)
        source += b'G92 E0\nG1 E-0.5 F1800\n'
        warp = with_paired_support_gap(self.warp, source, {0: '1'}, '1', vertical_gap_mm=.35)
        result = process_conformal_gcode(source, warp, {0: '1'}, '1')
        moves = list(read(result.gcode, set(), {0: '1'}).moves.values())
        model = [m for m in moves if m.deposits and m.role == 'outer wall']
        self.assertAlmostEqual(sum(m.de for m in model), 1., places=7)
        self.assertTrue(all(m.e_abs for m in model))
        self.assertAlmostEqual(moves[-1].e, -.5)
        self.assertAlmostEqual(moves[-1].de, -.5)

    def test_invalid_gaps_and_ceiling_below_fixed_base_are_rejected(self):
        for gap in (float('nan'), -.1, 0, 1.1):
            with self.subTest(gap=gap), self.assertRaises(WaveError):
                with_paired_support_gap(self.warp, SOURCE, {0: '1'}, '1', vertical_gap_mm=gap)
        with self.assertRaises(WaveError):
            with_paired_support_gap(self.warp, SOURCE.replace(b'7.2', b'0.8'), {0: '1'}, '1', vertical_gap_mm=.35)


if __name__ == '__main__':
    unittest.main()
