    def test_processed_top_and_first_bottom_layer_restore_both_analytic_skins(self):
        source,_=roof_coupon(25)
        w=RegionalShellWarp(source,'1',{'retain_native_short_edges':True})
        lines=['; generated by OrcaSlicer 2.5.1','G90','M83','G92 E0','G1 X105 Y110 Z0.2 F1200']
        for z,role in ((w.flat_bottom_z+.2,'Bottom surface'),(w.flat_top_z,'Top surface')):
            lines+=[';LAYER_CHANGE',f';Z:{z}',';HEIGHT:0.2',
                    '; printing object roof id:0 copy 0',f'G1 X105 Y110 Z{z} F1200',
                    f';TYPE:{role}',';WIDTH:0.42','G1 X115 E1 F600','G1 Y111 E0.1',
                    '; stop printing object roof id:0 copy 0']
        result=process_conformal_gcode(('\n'.join(lines)+'\n').encode(),w,{0:'1'},'1')
        parsed=read(result.gcode,set(),{0:'1'})
        changed=set();extrusion={'top surface':0.,'bottom surface':0.}
        for m in parsed.moves.values():
            if not m.deposits:continue
            extrusion[m.role]+=m.de
            if abs(m.end[2]-m.start[2])>2e-6:changed.add(m.role)
            expected=w.expected_surface(*m.end[:2],face='top' if m.role=='top surface' else 'bottom')
            # G-code Z denotes the bead's upper plane; first bottom layer has
            # a 0.2 mm vertical cell, whose lower plane is the original skin.
            physical_surface=m.end[2]-(.2 if m.role=='bottom surface' else 0.)
            self.assertAlmostEqual(physical_surface,expected,places=5)
        self.assertEqual(changed,{'top surface','bottom surface'})
        for value in extrusion.values():self.assertAlmostEqual(value,1.1,places=7)
        self.assertGreaterEqual(result.report['min_subdivided_segment_mm'],.15-2e-6)
        self.assertLessEqual(result.report['max_geometric_error_mm'],.02)
        self.assertFalse(result.report['print_allowed'])
