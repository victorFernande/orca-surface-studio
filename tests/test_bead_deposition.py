class VerticalWarp:
    anchor_z=.4
    object_id='part'
    settings=SimpleNamespace(step_mm=.4,min_segment_mm=.15,tolerance_mm=.02,retain_native_short_edges=True)
    deposition_model={'model':'logical_pitch_finite_bead_v1','profile_minimum_mm':.07,'profile_maximum_mm':.45}
    def map_point(self,p):return p[0],p[1],p[2] if p[2]<=.4 else .4+2*(p[2]-.4)
    def normal_gap(self,x,y,z,h):return self.map_point((x,y,z))[2]-self.map_point((x,y,z-h))[2]
    def volume_scale(self,x,y,z,h):return self.normal_gap(x,y,z,h)/h
    def surface_heights(self,x,y):return None
    def chord_error_bound(self,a,b,p,q):
        probes=[0.,.5,1.]
        if b[2]!=a[2]:probes.append(max(0.,min(1.,(.4-a[2])/(b[2]-a[2]))))
        return max(math.dist(self.map_point(tuple(x+t*(y-x) for x,y in zip(a,b))),
                             tuple(x+t*(y-x) for x,y in zip(p,q))) for t in probes)


def code(absolute=False):
    lines=['; generated by OrcaSlicer 2.5.1','G90','M82' if absolute else 'M83','G92 E0','G0 X0 Y0 Z0.2 F1200']
    e=0.
    for layer in range(6):
        z=.2*(layer+1);bridge=layer==3;e+=.1
        lines+=[';LAYER_CHANGE',f';Z:{z:.6f}',';HEIGHT:'+('.36' if bridge else '.2'),
            '; printing object A id:0 copy 0',f'G0 X0 Z{z:.6f}',
            ';TYPE:'+('Bridge' if bridge else 'Outer wall'),';WIDTH:'+('.36' if bridge else '.5'),
            f'G1 X2 E{e:.6f}' if absolute else 'G1 X2 E0.1','; stop printing object A id:0 copy 0']
    lines+=['; printing object B id:1 copy 0',';TYPE:Outer wall',';HEIGHT:0.2',';WIDTH:0.5','G0 X4 Z1.2',
            'G1 X5 E0.7 ;control' if absolute else 'G1 X5 E0.1 ;control',
            '; stop printing object B id:1 copy 0','G92 E0','G1 E-0.5 ;after-reset']
    return ('\n'.join(lines)+'\n').encode()


class BeadDepositionTests(unittest.TestCase):
    def test_spacing_regrid_preserves_whole_affine_cells_hole_and_source_mesh(self):
        from test_bending import roof_with_hole,euler
        from orca_wave_studio.surface import SurfaceMesh,SurfaceSettings
        snapshot=roof_with_hole();original=snapshot.to_dict()
        warp=ContinuousLayerWarp(snapshot,'1',RegionalShellSettings(nominal_layer_height_mm=.2,tolerance_mm=.02),initial_layer_mm=.2)
        before=list(warp.flat_world_vertices);bound=warp.summary['mesh_normal_and_crease_error_budget_mm']
        grid=LayerGridStage([0.,.4,59.6,70.],[0.,.4,30.,70.])
        warp.regrid_spacing(grid,{'extra_slice_intervals':12},initial_layer_mm=.2)
        self.assertEqual(snapshot.to_dict(),original)
        self.assertEqual(bound,warp.summary['mesh_normal_and_crease_error_budget_mm'])
        self.assertTrue(all(r['core_in_one_native_band'] for r in warp.summary['reference_alignment']))
        SurfaceMesh(warp.flattened_snapshot.objects[0],SurfaceSettings())
        self.assertEqual(euler(warp.flattened_snapshot.objects[0]),0)
        for old,new in zip(before,warp.flat_world_vertices):self.assertLess(math.dist(old,grid.map_point(new)),1e-9)
        for tri in warp.flattened_snapshot.objects[0]['volumes'][0]['triangles']:
            self.assertLess(grid.mapped_triangle_error([warp.flat_world_vertices[k] for k in tri]),1e-7)

    def test_height_width_and_e_match_finite_section_for_relative_and_absolute_extrusion(self):
        outputs=[]
        for absolute in (False,True):
            result=process_conformal_gcode(code(absolute),VerticalWarp(),{0:'part',1:'control'},'part')
            parsed=read(result.gcode,set(),{0:'part',1:'control'},require_planar=False)
            totals={}
            for m in parsed.moves.values():
                if not m.deposits:continue
                totals[m.obj]=totals.get(m.obj,0)+m.de
                if m.obj=='part' and m.role=='outer wall':
                    expected=.2 if m.layer<2 else .4
                    self.assertAlmostEqual(m.h,expected,places=5)
                    self.assertAlmostEqual(m.w,.5,places=5)
                if m.obj=='part' and m.role=='bridge':
                    self.assertAlmostEqual(m.h,.36,places=5)
                if m.obj=='control':self.assertAlmostEqual(m.h,.2,places=6)
            expected=.3+.3*section_area(.5,.4)/section_area(.5,.2)
            self.assertAlmostEqual(totals['part'],expected,places=6)
            self.assertAlmostEqual(totals['control'],.1,places=6)
            self.assertIn(b'G92 E0\nG1 E-0.5 ;after-reset',result.gcode)
            self.assertEqual(result.report['bead_deposition']['above_profile_maximum_occurrences'],0)
            self.assertFalse(result.report['print_allowed']);outputs.append(totals)
        self.assertAlmostEqual(outputs[0]['part'],outputs[1]['part'],places=7)

    def test_bridge_feature_height_does_not_replace_the_logical_pitch(self):
        parsed=read(code(),set(),{0:'part',1:'control'})
        self.assertAlmostEqual(layer_pitches(parsed,'part')[3],.2)
        m=next(m for m in parsed.moves.values() if m.obj=='part' and m.role=='bridge' and m.deposits)
        e,h,w,gaps=bead_portion(VerticalWarp(),m.start,m.end,m,m.de,.2)
        self.assertAlmostEqual(e,m.de);self.assertEqual(h,.36);self.assertIsNone(gaps)

    def test_unsupported_height_is_refused_and_cancellation_remains_responsive(self):
        warp=VerticalWarp();warp.deposition_model={**warp.deposition_model,'profile_maximum_mm':.28}
        with self.assertRaisesRegex(WaveError,'BEAD_HEIGHT'):
            process_conformal_gcode(code(),warp,{0:'part',1:'control'},'part')
        with self.assertRaisesRegex(WaveError,'cancelada'):
            process_conformal_gcode(code(),VerticalWarp(),{0:'part',1:'control'},'part',cancelled=lambda:True)

    def test_normal_gap_and_tilt_both_contribute_to_extrusion(self):
        class Tilt:
            def map_point(self,p):return p[0],p[1],p[2]+.3*p[0]
            def normal_gap(self,x,y,z,h):return h/math.hypot(1.,.3)
        move=SimpleNamespace(role='outer wall',h=.2,w=.5)
        e,h,w,gaps=bead_portion(Tilt(),(0,0,2),(2,0,2),move,.1,.2)
        expected=.1*section_area(.5,.2/math.hypot(1,.3))/section_area(.5,.2)*math.hypot(1,.3)
        self.assertAlmostEqual(e,expected,places=12)
        self.assertNotAlmostEqual(e,.1*math.hypot(1,.3),places=5)
        with self.assertRaisesRegex(WaveError,'BEAD_SECTION'):section_area(.2,.3)

    def test_interval_cell_bound_contains_interior_xy_points_and_vertical_knots(self):
        points=[(x,y,9+.1*x+.006*x*x+.004*x*y) for x in np.linspace(0,10,8) for y in (0.,8.)]
        field=HeightField(points,np.ones(len(points)));stage=SurfaceStage(field,1.,20.)
        grid=LayerGridStage([0.,4.,8.,15.,22.],[0.,3.,10.,16.,22.])
        warp=ContinuousLayerWarp.__new__(ContinuousLayerWarp);warp.stages=[stage,grid]
        left=[];right=[];pitches=[]
        for z in (3.95,4.,4.05,7.95,8.05,10.,15.,18.):
            left.append((-.2,1.,z));right.append((10.2,7.,z));pitches.append(.24)
        bound=cell_vertical_scale_upper(warp.stages,left,right,pitches)
        for a,b,pitch,maximum in zip(left,right,pitches,bound):
            for x in np.linspace(a[0],b[0],15):
                for y in np.linspace(a[1],b[1],9):
                    delta=warp.map_point((x,y,a[2]))[2]-warp.map_point((x,y,a[2]-pitch))[2]
                    self.assertLessEqual(delta/pitch,maximum+1e-8)

    def test_exact_first_grid_secant_does_not_repeat_boundary_refinement(self):
        grid=LayerGridStage([0.,.4,.8,2.],[0.,.4,.6,2.])
        bound=cell_vertical_scale_upper([grid],[(0,0,.8)],[(2,0,.8)],[.2])
        self.assertAlmostEqual(bound[0],.5,places=12)

    def test_spacing_plan_preserves_first_layer_and_inserts_phase_aligned_intervals(self):
        warp=VerticalWarp();warp.stages=[LayerGridStage([0.,.4,1.,4.],[0.,.4,1.6,4.])]
        warp.flat_world_vertices=((0,0,1.2),)
        grid,plan=plan_spacing(code(),warp,{0:'part',1:'control'},'part',.28,.2,250.)
        self.assertGreater(plan['extra_slice_intervals'],0)
        self.assertEqual(grid.map_point((0,0,.2))[2],.2)
        for z in (.2,.4,.6,.8,1.,1.2):
            target=grid.flatten_point((0,0,z))[2]
            self.assertAlmostEqual(target/.2,round(target/.2),places=8)


if __name__=='__main__':unittest.main()
